"""Extract Docker Desktop's official Markdown allowlist."""

import argparse
import csv
import io
from pathlib import Path
import re
from urllib.parse import urlsplit

from build_lists import ROOT, download, parse_domains

URL = "https://docs.docker.com/desktop/enterprise/allow-list.md"


def extract(markdown):
    rows = []
    in_table = False
    found = False
    for line in markdown.splitlines():
        cells = [cell.strip() for cell in line.strip().strip("|").split("|")]
        if cells == ["Domains", "Description"]:
            if found:
                raise ValueError("Duplicate Docker domain table")
            found = in_table = True
            continue
        if not in_table:
            continue
        if not line.strip().startswith("|"):
            in_table = False
            continue
        if all(re.fullmatch(r":?-+:?", cell) for cell in cells):
            continue
        if len(cells) != 2:
            raise ValueError(f"Unexpected Docker table row: {line}")
        url, description = cells
        parsed = urlsplit(url)
        if (parsed.scheme != "https" or not parsed.hostname or parsed.username
                or parsed.password or parsed.port or parsed.path not in ("", "/")
                or parsed.query or parsed.fragment):
            raise ValueError(f"Unexpected Docker domain URL: {url}")
        hosts = parse_domains(parsed.hostname, URL)
        if len(hosts) != 1:
            raise ValueError(f"Invalid Docker host: {url}")
        rows.append([next(iter(hosts)), url, description])
    hosts = {row[0] for row in rows}
    if len(hosts) < 10 or not {"auth.docker.io", "registry-1.docker.io"} <= hosts:
        raise ValueError("Docker extraction incomplete; review source layout")
    return hosts, rows


def update(markdown):
    hosts, rows = extract(markdown)
    content = f"# Source: {URL}\n# Generated by scripts/update_docker.py; wildcards preserved.\n"
    content += "".join(host + "\n" for host in sorted(hosts))
    details = io.StringIO()
    writer = csv.writer(details)
    writer.writerow(["host", "url", "description"])
    writer.writerows(rows)
    (ROOT / "lists/allow/docker.txt").write_text(content, encoding="utf-8")
    directory = ROOT / "metadata"
    directory.mkdir(exist_ok=True)
    (directory / "docker.csv").write_text(details.getvalue(), encoding="utf-8")
    print(f"Docker: {len(hosts)} unique hosts, {len(rows)} endpoint rows")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--markdown", type=Path, help="Use a previously downloaded Markdown file")
    args = parser.parse_args()
    update(args.markdown.read_text(encoding="utf-8") if args.markdown else download(URL))
