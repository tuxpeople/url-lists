#!/usr/bin/env bash
# Synchronize subscribed regex lists with Pi-hole; use --dry-run for a preview.
set -euo pipefail
export LC_ALL=C
umask 077

REGEXLISTS=()
container=pihole
rule_type=allow
managed_comment='managed by script'
dry_run=false

usage() {
    cat <<'HELP'
Usage: bash scripts/regex_import.sh [options]

Compare subscribed regex lists with the live Pi-hole JSON API.
Apply changes and verify each batch through the JSON API.

  --url HTTPS_URL       Subscribe to this URL (repeatable; replaces defaults)
  --container NAME     Pi-hole Docker container (default: pihole)
  --type allow|deny    Regex rule type (default: allow)
  --comment TEXT       Exact ownership marker (default: managed by script)
  --dry-run            Display changes without applying them
  --help               Show this help

Defaults: combined allow-regex.txt or block-regex.txt for the selected type.
Requires Bash, curl, Docker and jq on the host. Empty lists are allowed.
No baseline file is read or saved. Disabled desired rules stay disabled.
HELP
}

while (($#)); do
    case "$1" in
        --url|--container|--type|--comment)
            [[ $# -ge 2 && -n "$2" ]] || { echo "Missing value for $1" >&2; exit 1; }
            case "$1" in
                --url) REGEXLISTS+=("$2") ;;
                --container) container="$2" ;;
                --type) rule_type="$2" ;;
                --comment) managed_comment="$2" ;;
            esac
            shift 2 ;;
        --dry-run) dry_run=true; shift ;;
        --help) usage; exit 0 ;;
        *) echo "Unknown option: $1" >&2; usage >&2; exit 1 ;;
    esac
done
[[ "$rule_type" == allow || "$rule_type" == deny ]] || { echo 'Type must be allow or deny' >&2; exit 1; }
# Match the comment characters supported by Pi-hole's CLI.
[[ "$managed_comment" != *[!a-zA-Z0-9_\#:/.,\ -]* ]] || { echo 'Unsupported comment characters' >&2; exit 1; }
[[ "$container" != -* ]] || { echo 'Invalid container name' >&2; exit 1; }
if ((${#REGEXLISTS[@]} == 0)); then
    if [[ "$rule_type" == allow ]]; then
        REGEXLISTS=(
            "https://raw.githubusercontent.com/tuxpeople/url-lists/main/pihole/allow-regex.txt"
        )
    else
        REGEXLISTS=("https://raw.githubusercontent.com/tuxpeople/url-lists/main/pihole/block-regex.txt")
    fi
fi
for dependency in curl docker jq; do
    command -v "$dependency" >/dev/null || { echo "Missing dependency: $dependency" >&2; exit 1; }
done
work_dir=$(mktemp -d "${TMPDIR:-/tmp}/url-lists-regex.XXXXXXXX")
lock_dir=''
cleanup() {
    rm -rf -- "$work_dir"
    if [[ -n "$lock_dir" ]]; then rmdir -- "$lock_dir"; fi
}
trap cleanup EXIT
trap 'exit 130' INT
trap 'exit 143' TERM
if [[ "$dry_run" == false ]]; then
    lock_root="${XDG_STATE_HOME:-${HOME}/.local/state}/url-lists"
    mkdir -p -- "$lock_root"
    lock_key=$(printf '%s/%s' "$container" "$rule_type" | cksum | awk '{print $1}')
    candidate="$lock_root/regex-sync-$lock_key.lock"
    if ! mkdir -- "$candidate" 2>/dev/null; then
        echo "Another sync holds the lock: $candidate" >&2
        exit 1
    fi
    lock_dir="$candidate"
fi
: > "$work_dir/combined"

for url in "${REGEXLISTS[@]}"; do
    [[ "$url" == https://* ]] || { echo "HTTPS required: $url" >&2; exit 1; }
    if ! curl --fail --silent --show-error --location \
        --proto '=https' --proto-redir '=https' \
        --connect-timeout 15 --max-time 60 --max-filesize 10485760 \
        --output "$work_dir/download" "$url"; then
        echo "Download failed; no changes planned: $url" >&2
        exit 1
    fi
    cat "$work_dir/download" >> "$work_dir/combined"
    printf '\n' >> "$work_dir/combined"
done

# Normalize CRLF, empty lines, ordering and duplicates.
sed 's/\r$//; /^[[:space:]]*$/d' "$work_dir/combined" | sort -u > "$work_dir/new"
while IFS= read -r pattern; do
    # Only the anchored, whitespace-free POSIX ERE format generated by this repo.
    if [[ "$pattern" != ^* || "$pattern" != *'$' || "$pattern" == *[[:space:][:cntrl:]]* ]]; then
        echo "Unexpected regex line: $pattern" >&2
        exit 1
    fi
    if grep -E -e "$pattern" /dev/null >/dev/null 2>&1; then
        :
    else
        status=$?
        if [[ "$status" -ne 1 ]]; then
            echo "Invalid POSIX regex: $pattern" >&2
            exit 1
        fi
    fi
done < "$work_dir/new"

fetch_api() {
# Deliberately no -i/-t: a terminal can contaminate the JSON output.
if ! docker exec "$container" pihole api "domains/$rule_type/regex" > "$work_dir/api.json"; then
    echo 'Pi-hole API query failed; synchronization stopped.' >&2
    exit 1
fi
# The CLI may return success even for API errors. Validate one complete response,
# every record, and unique domains before treating an empty array as authoritative.
if ! jq -e -s '
    def safe_line: type == "string" and length > 0 and (test("[\\x00-\\x1f\\x7f]") | not);
    length == 1 and (.[0] |
        type == "object" and (.error? == null) and
        (.domains | type == "array") and
        all(.domains[];
            (.domain | safe_line) and
            (.comment == null or (.comment | type == "string")) and
            (.enabled | type == "boolean") and
            (.groups | type == "array") and
            all(.groups[]; type == "number" and . >= 0 and . == floor)) and
        (([.domains[].domain] | unique | length) == (.domains | length)))
' "$work_dir/api.json" >/dev/null; then
    echo 'Invalid Pi-hole API response; synchronization stopped.' >&2
    exit 1
fi
}

# Ignore IDs/timestamps, but retain all fields whose semantics we must preserve.
canonical_state() {
    jq -S '.domains | map({domain, comment: (.comment // null), enabled,
                          groups: (.groups | sort)}) | sort_by(.domain)' "$1"
}
fetch_api
cp "$work_dir/api.json" "$work_dir/snapshot.json"
jq -r '.domains[].domain' "$work_dir/api.json" | sort -u > "$work_dir/all"
jq -r --arg marker "$managed_comment" \
    '.domains[] | select(.comment == $marker) | .domain' \
    "$work_dir/api.json" | sort -u > "$work_dir/managed"
jq -r --arg marker "$managed_comment" \
    '.domains[] | select(.comment != $marker) | .domain' \
    "$work_dir/api.json" | sort -u > "$work_dir/unmanaged"
jq -r --arg marker "$managed_comment" \
    '.domains[] | select(.comment == $marker and .enabled == false) | .domain' \
    "$work_dir/api.json" | sort -u > "$work_dir/disabled"
comm -23 "$work_dir/managed" "$work_dir/new" > "$work_dir/removed"
comm -13 "$work_dir/all" "$work_dir/new" > "$work_dir/added"
comm -12 "$work_dir/disabled" "$work_dir/new" > "$work_dir/disabled-desired"
printf 'Removed filters (managed only)\n'
cat "$work_dir/removed"
printf '\nAdded filters\n'
cat "$work_dir/added"
printf '\nExisting unmanaged filters (left unchanged, including groups/enabled state)\n'
cat "$work_dir/unmanaged"
printf '\nDisabled managed filters still desired (left disabled)\n'
cat "$work_dir/disabled-desired"

# Logging uses Bash quoting; execution passes arguments directly, never via eval.
run_command() {
    local action="$1"
    shift
    printf 'docker exec'
    printf ' %q' "$container" pihole "$@"
    printf '\n'
    if [[ "$dry_run" == true ]]; then return; fi

    # Refuse stale plans if a person or another integration changed the rules.
    fetch_api
    canonical_state "$work_dir/snapshot.json" > "$work_dir/expected"
    canonical_state "$work_dir/api.json" > "$work_dir/actual"
    if ! cmp -s "$work_dir/expected" "$work_dir/actual"; then
        echo 'Pi-hole changed since planning; stopped. Run again to re-plan.' >&2
        exit 1
    fi
    if ! docker exec "$container" pihole "$@"; then
        echo 'Pi-hole command failed; stopped. Earlier batches may already be applied.' >&2
        exit 1
    fi
    fetch_api
    jq -Rn '[inputs]' < "$work_dir/batch" > "$work_dir/batch.json"
    jq -S --slurpfile batch "$work_dir/batch.json" --arg marker "$managed_comment" \
        --arg action "$action" '
        if $action == "add" then
            . + ($batch[0] | map({domain: ., comment: $marker, enabled: true, groups: [0]}))
        else
            map(select(.domain as $d | ($batch[0] | index($d)) == null))
        end | sort_by(.domain)
    ' "$work_dir/expected" > "$work_dir/after-expected"
    canonical_state "$work_dir/api.json" > "$work_dir/actual"
    if ! cmp -s "$work_dir/after-expected" "$work_dir/actual"; then
        echo 'Pi-hole result differs from the plan; stopped. Changes may be partially applied; run again to re-plan.' >&2
        exit 1
    fi
    cp "$work_dir/api.json" "$work_dir/snapshot.json"
}

print_commands() {
    local file="$1" action="$2" pattern
    shift 2
    local batch=()
    while IFS= read -r pattern; do
        batch+=("$pattern")
        # Keep commands manageable for larger lists.
        if ((${#batch[@]} == 100)); then
            printf '%s\n' "${batch[@]}" > "$work_dir/batch"
            run_command "$action" "$@" "${batch[@]}"
            batch=()
        fi
    done < "$file"
    if ((${#batch[@]})); then
        printf '%s\n' "${batch[@]}" > "$work_dir/batch"
        run_command "$action" "$@" "${batch[@]}"
    fi
}

if [[ "$dry_run" == true ]]; then
    printf '\nPi-hole commands (preview only; not executed)\n'
else
    printf '\nApplying Pi-hole changes\n'
fi
if [[ ! -s "$work_dir/added" && ! -s "$work_dir/removed" ]]; then
    printf 'No changes.\n'
else
    if [[ "$rule_type" == allow ]]; then regex_option=--allow-regex; else regex_option=--regex; fi
    # Add first to avoid a gap when replacing narrower allow rules with a broader one.
    print_commands "$work_dir/added" add "$regex_option" --comment "$managed_comment"
    print_commands "$work_dir/removed" remove "$regex_option" remove
fi
if [[ "$dry_run" == true ]]; then
    printf '\nPreview only: Pi-hole unchanged.\n'
else
    fetch_api
    canonical_state "$work_dir/snapshot.json" > "$work_dir/expected"
    canonical_state "$work_dir/api.json" > "$work_dir/actual"
    if ! cmp -s "$work_dir/expected" "$work_dir/actual"; then
        echo 'Pi-hole changed during final verification; run again to re-plan.' >&2
        exit 1
    fi
    printf '\nSynchronization verified successfully.\n'
fi
