"""Extract table endpoints, preserving categories and conditions for later splits."""

import argparse
import csv
import io
from pathlib import Path
import re
from urllib.parse import urlsplit

from build_lists import ROOT, download, parse_domains

URL = "https://github.com/openshift/openshift-docs/raw/refs/heads/main/modules/configuring-firewall-module.adoc"
CLOUDS = {"Alibaba", "AWS", "GCP", "Microsoft Azure"}


def extract(document):
    rows = []
    conditions = []
    category = ""
    table = None
    table_context = None
    for line in document.splitlines():
        if line.startswith("//"):
            continue
        if re.match(r"(?:ifdef|ifndef|ifeval)::", line):
            conditions.append(line)
        elif line.startswith("endif::"):
            if not conditions:
                raise ValueError("Unbalanced AsciiDoc conditions")
            conditions.pop()
        if line.startswith(". "):
            category = line[2:].strip()
        if line.strip() == "|===":
            if table is None:
                table = []
                table_context = (category, "; ".join(conditions))
            else:
                rows.extend(parse_table(table, *table_context))
                table = None
            continue
        if table is not None:
            match = re.match(r"^(?:\.\d+\+)?\|(.*)$", line)
            if match:
                table.extend(cell.strip() for cell in match[1].split("|"))
            elif line.strip() and table:
                table[-1] += " " + line.strip()
    if table is not None or conditions:
        raise ValueError("Incomplete AsciiDoc source")
    hosts = {row[4] for row in rows if row[5] == "included"}
    if len(hosts) < 25 or not {"quay.io", "registry.redhat.io", "api.openshift.com"} <= hosts:
        raise ValueError("OpenShift extraction incomplete; review source layout")
    return hosts, rows


def parse_table(cells, category, condition):
    cloud_table = cells[:4] == ["Cloud", "URL", "Port", "Function"]
    header_size = 4 if cloud_table else 3
    if not cloud_table and cells[:3] != ["URL", "Port", "Function"]:
        raise ValueError(f"Unexpected OpenShift table headers: {cells[:4]}")
    index = header_size
    cloud = ""
    rows = []
    while index < len(cells):
        if cloud_table and cells[index] in CLOUDS:
            cloud = cells[index]
            index += 1
        if cloud_table and not cloud:
            raise ValueError("Cloud endpoint without provider")
        if index + 3 > len(cells):
            raise ValueError("Incomplete OpenShift table row")
        target_cell, port, description = cells[index:index + 3]
        index += 3
        match = re.match(r"^`([^`]+)`(?:\s|$)", target_cell)
        if not match or not port:
            raise ValueError(f"Unexpected OpenShift endpoint: {target_cell}")
        target = match[1]
        host = ""
        status = "requires-substitution" if re.search(r"[<>{}]", target) else "included"
        if status == "included":
            parsed = urlsplit(target if "://" in target else "https://" + target)
            if not parsed.hostname or parsed.username or parsed.password or parsed.port or parsed.query or parsed.fragment:
                raise ValueError(f"Unsupported OpenShift endpoint: {target}")
            host = parsed.hostname
            parse_domains(host, URL)
        rows.append([category, cloud, condition, target, host, status, port, description])
    return rows


def update(document):
    hosts, rows = extract(document)
    content = f"# Source: {URL}\n# Generated by scripts/update_openshift.py; placeholders excluded; wildcards preserved.\n"
    content += "".join(host + "\n" for host in sorted(hosts))
    details = io.StringIO()
    writer = csv.writer(details)
    writer.writerow(["category", "cloud", "condition", "target", "host", "status", "port", "description"])
    writer.writerows(rows)
    (ROOT / "lists/allow/openshift.txt").write_text(content, encoding="utf-8")
    directory = ROOT / "metadata"
    directory.mkdir(exist_ok=True)
    (directory / "openshift.csv").write_text(details.getvalue(), encoding="utf-8")
    print(f"OpenShift: {len(hosts)} unique hosts, {len(rows)} endpoint rows")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--asciidoc", type=Path, help="Use a previously downloaded AsciiDoc file")
    args = parser.parse_args()
    update(args.asciidoc.read_text(encoding="utf-8") if args.asciidoc else download(URL))
