"""Extract host table data from Apple's enterprise network documentation."""

import argparse
import csv
from html.parser import HTMLParser
import io
from pathlib import Path

from build_lists import ROOT, download, parse_domains

URL = "https://support.apple.com/en-us/101555"


class Tables(HTMLParser):
    def __init__(self):
        super().__init__()
        self.rows = []
        self.row = None
        self.cell = None
        self.category = ""
        self.subcategory = ""
        self.heading = None
        self.heading_tag = None

    def handle_starttag(self, tag, attrs):
        if tag in ("h2", "h3"):
            self.heading = []
            self.heading_tag = tag
        elif tag == "tr":
            self.row = []
        elif tag in ("td", "th") and self.row is not None:
            self.cell = []
        elif tag == "br" and self.cell is not None:
            self.cell.append(" ")

    def handle_data(self, data):
        if self.cell is not None:
            self.cell.append(data)
        if self.heading is not None:
            self.heading.append(data)

    def handle_endtag(self, tag):
        if tag == self.heading_tag:
            title = " ".join("".join(self.heading).split())
            if tag == "h2":
                self.category = title
                self.subcategory = ""
            else:
                self.subcategory = title
            self.heading = self.heading_tag = None
        elif tag in ("td", "th") and self.cell is not None:
            self.row.append(" ".join("".join(self.cell).split()))
            self.cell = None
        elif tag == "tr" and self.row is not None:
            self.rows.append((self.category, self.subcategory, self.row))
            self.row = None


def extract(html):
    parser = Tables()
    parser.feed(html)
    rows = []
    for category, subcategory, row in parser.rows:
        if row and row[0] == "Hosts":
            continue
        if len(row) != 6:
            raise ValueError(f"Unexpected Apple table row: {row!r}")
        parse_domains(row[0], URL)
        if not row[1] or not row[2]:
            raise ValueError("Missing port or protocol")
        if not category:
            raise ValueError("Apple endpoint table has no category")
        rows.append([category, subcategory, *row])
    hosts = set().union(*(parse_domains(row[2], URL) for row in rows))
    if len(hosts) < 80 or "albert.apple.com" not in hosts or "*.push.apple.com" not in hosts:
        raise ValueError("Apple extraction incomplete; review source layout")
    return hosts, rows


def update(html):
    hosts, rows = extract(html)
    content = f"# Source: {URL}\n# Generated by scripts/update_apple.py; wildcards preserved.\n"
    content += "".join(host + "\n" for host in sorted(hosts))
    details = io.StringIO()
    writer = csv.writer(details)
    writer.writerow(["category", "subcategory", "hosts", "ports", "protocol", "os", "description", "supports_proxies"])
    writer.writerows(rows)
    (ROOT / "lists/allow/apple.txt").write_text(content, encoding="utf-8")
    directory = ROOT / "metadata"
    directory.mkdir(exist_ok=True)
    (directory / "apple.csv").write_text(details.getvalue(), encoding="utf-8")
    print(f"Apple: {len(hosts)} unique hosts, {len(rows)} endpoint rows")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--html", type=Path, help="Use a previously downloaded HTML file")
    args = parser.parse_args()
    update(args.html.read_text(encoding="utf-8") if args.html else download(URL))
